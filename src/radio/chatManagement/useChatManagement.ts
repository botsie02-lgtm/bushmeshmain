import {useCallback, useEffect, useRef, useState} from 'react';
import {useRadioConnection} from '../../state/RadioConnectionContext';
import {
  ChatConfiguration, ChatPersonalisation, ChatPreferencePatch, ChatPreferenceSnapshot, ChatSort, chatPreferenceStore,
} from './chatPreferences';
import {ChatOperationError} from './chatInvitations';

/** Mount once in the messenger; use the returned controller for inbox and rooms. */
export function useChatManagement() {
  const connection = useRadioConnection();
  const radio = connection.getChatRadio();
  const sessionEpoch = connection.getChatSessionEpoch();
  const live = useRef(connection);
  live.current = connection;
  const busyRef = useRef(false);
  const refreshFlight = useRef<Promise<void> | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [loadedRadio, setLoadedRadio] = useState<string | null>(null);
  const [loadedEpoch, setLoadedEpoch] = useState<number | null>(null);
  const [configs, setConfigs] = useState<ChatConfiguration[]>([]);
  const [preferences, setPreferences] = useState<ChatPreferenceSnapshot>({});
  const [ready, setReady] = useState(false);
  const [catalogueStatus, setCatalogueStatus] = useState<'loading' | 'ready' | 'error'>('loading');
  const currentPreferences = useRef(preferences);
  currentPreferences.current = preferences;
  const [sort, setSort] = useState<ChatSort>('recent');
  useEffect(() => {
    let active = true;
    chatPreferenceStore.loadState().then(({entries, sort: savedSort}) => {
      if (active && !busyRef.current) {setPreferences(entries); setSort(savedSort);setCatalogueStatus('ready');}
    }).catch(() => {if (active && !busyRef.current) {setCatalogueStatus('error');setError('Saved chats could not be restored.');}});
    return () => {active = false;};
  }, []);

  const run = useCallback(async <T,>(action: () => Promise<T>): Promise<T> => {
    if (busyRef.current) throw new Error('Chat management is busy.');
    busyRef.current = true;
    setBusy(true);
    setError(null);
    try {
      return await action();
    } catch (failure) {
      // Do not surface raw bridge errors: some inputs are channel credentials.
      // Only typed errors generated by our own service may cross the UI boundary.
      setError(failure instanceof ChatOperationError ? failure.message :
        'Chat operation could not be confirmed. Refresh chats before retrying.');
      throw failure;
    } finally {
      busyRef.current = false;
      setBusy(false);
    }
  }, []);

  const reload = useCallback(async (expected: string) => {
    setReady(false);
    const expectedEpoch = live.current.getChatSessionEpoch();
    const {sort: savedSort} = await chatPreferenceStore.loadState();
    const next = await live.current.listChatConfigurations(expected);
    if (live.current.getChatRadio() !== expected ||
        live.current.getChatSessionEpoch() !== expectedEpoch) throw new Error('Radio changed.');
    const entries = await chatPreferenceStore.rememberConfigurations(expected, next);
    if (live.current.getChatRadio() !== expected || live.current.getChatSessionEpoch() !== expectedEpoch) throw new Error('Radio changed.');
    setPreferences(entries);
    setCatalogueStatus('ready');
    setSort(savedSort);
    setConfigs(next);
    setLoadedRadio(expected);
    setLoadedEpoch(expectedEpoch);
    setReady(true);
  }, []);

  const refresh = useCallback(() => {
    if (refreshFlight.current) return refreshFlight.current;
    const expected = live.current.getChatRadio();
    if (!expected) return Promise.reject(new Error('Connect a radio and sync its identity first.'));
    const flight = run(() => reload(expected)).finally(() => {refreshFlight.current = null;});
    refreshFlight.current = flight;
    return flight;
  }, [reload, run]);

  useEffect(() => {
    setReady(false);
    setLoadedRadio(null);
    setLoadedEpoch(null);
    setError(null);
    // The host may request a refresh after the radio is idle; no write occurs here.
  }, [radio, sessionEpoch]);

  const requireCurrent = (chat: ChatConfiguration) => {
    if (!ready || loadedEpoch !== live.current.getChatSessionEpoch() || loadedRadio !== chat.radio ||
        live.current.getChatRadio() !== chat.radio ||
        !configs.some(c => c.id === chat.id)) {
      throw new Error('Chat changed. Refresh chats.');
    }
  };

  const update = (chat: ChatConfiguration, patch: ChatPreferencePatch) =>
    run(async () => {
      requireCurrent(chat);
      // Even local preferences must not be edited through a stale live row.
      try {
        await live.current.verifyChatConfiguration(chat);
      } catch (failure) {
        setReady(false);
        throw failure;
      }
      // Purely local changes are keyed to the selected configuration, not a slot.
      const entries = await chatPreferenceStore.update(chat.id, patch);
      if (live.current.getChatRadio() === chat.radio) setPreferences(entries);
    });

  const updateLocal = (id: string, patch: ChatPreferencePatch, incarnation?: number) => chatPreferenceStore.update(id, patch, incarnation).then(entries => {setPreferences(entries);});

  const changeSort = (next: ChatSort) => run(async () => {
    const expected = live.current.getChatRadio();
    if (!ready || loadedEpoch !== live.current.getChatSessionEpoch() || !expected || loadedRadio !== expected || configs.length === 0) {
      throw new Error('Refresh a configured radio before changing sort.');
    }
    await chatPreferenceStore.saveSort(next);
    setSort(next);
  });

  const provision = (expectedRadio: string, input: {name: string; secretHex?: string; personalisation?: Partial<ChatPersonalisation>}) =>
    run(async () => {
      if (live.current.getChatRadio() !== expectedRadio) throw new Error('Radio changed.');
      try {
        const chat = await live.current.provisionChat(expectedRadio, input);
        try {
          await reload(expectedRadio);
        } catch {
          throw new ChatOperationError('partial', 'Chat was configured, but the updated list could not be verified. Refresh before retrying.');
        }
        return chat;
      } catch (failure) {
        setReady(false);
        throw failure;
      }
    });

  const leave = (chat: ChatConfiguration, onRemoved?: () => void, incarnation?: number) => run(async () => {
    requireCurrent(chat);
    if (incarnation !== undefined && ((currentPreferences.current[chat.id]?.incarnation ?? 1) !== incarnation || currentPreferences.current[chat.id]?.retired)) throw new ChatOperationError('stale', 'Chat configuration changed. Refresh before removing it.');
    setReady(false);
    setError('Removing channel… You can navigate back.');
    let removed = false;
    const confirmed = () => {
      if (removed) return;
      removed = true;
      setConfigs(current => current.filter(c => c.id !== chat.id));
      setPreferences(current => current[chat.id] ? {...current, [chat.id]: {...current[chat.id], retired: true}} : current);
      setError('Channel removed. Refreshing radio…');
      onRemoved?.();
    };
    try {
      await live.current.leaveChat(chat, phase => {
        if (phase === 'removed') confirmed();
        else setError(phase === 'removing' ? 'Removing channel…' : 'Verifying channel removal…');
      });
      confirmed();
    } catch (failure) {
      setReady(false);
      if (!removed) {
        if (failure instanceof ChatOperationError && (failure.code === 'partial' || failure.code === 'rejected')) throw failure;
        throw new ChatOperationError('stale', 'Channel removal rejected or not started. Refresh before retrying.');
      }
      setError('Channel removed, but protected retirement failed. Refresh before using this radio.');
      return;
    }
    try {
      await reload(chat.radio);
      setError('Channel removed. Saved history retained.');
    } catch {
      setError('Channel removed successfully, but refresh failed. Refresh chats before sending.');
    }
  });

  const credential = (chat: ChatConfiguration) => run(async () => {
    requireCurrent(chat);
    try {
      const value = await live.current.revealChatCredential(chat);
      requireCurrent(chat);
      return value;
    } catch (failure) {
      setReady(false);
      throw failure;
    }
  });

  const current = ready && radio === loadedRadio && loadedEpoch === sessionEpoch;
  return {
    radio, sessionEpoch, busy, error,
    capacity: radio && current
      ? {used: configs.length, total: connection.snapshot.channels.length} : null,
    ready: current,
    // Display cache only: all transport operations continue to require current.
    chats: configs,
    preferences, catalogueStatus,
    refresh, update, provision, leave, credential, sort, changeSort,
    updateLocal,
    invalidate: () => setReady(false),
    isCurrentRadio: (expected: string) => live.current.getChatRadio() === expected,
    radioBusy: connection.snapshot.isWriting,
  };
}

export type ChatManagementController = ReturnType<typeof useChatManagement>;
